package io.github.sweetzonzi.machine_max.common.mech.part;

/**
 * 动态存档中哪些状态可被用于构造实例的显式策略。
 *
 * <p>坐标归一化只负责摆放位置，不代表清除了库存或制造进度。调用者必须根据收纳物品、蓝图等
 * 用途选择模式；具体种类的恢复回调负责执行该策略，工厂不会自动重写输入 DTO。</p>
 */
public enum PartRestoreMode {
    /**
     * 完整恢复：在结构和身份之外，加载保存的耐久、涂装、制造进度、连接点与子系统状态。
     * 用于收纳物品、世界存档和服务端实例状态的客户端重建。
     */
    FULL_STATE,
    /**
     * 仅恢复骨架：保留部件身份、变体、子零件集合及位姿，不加载模板保存的运行资源与损伤。
     * 普通部件的组装和材料进度置零，使用默认涂装并显示线框；子系统保留新建时的默认状态。
     * 用于需要重新投入材料组装的蓝图。
     */
    STRUCTURE_ONLY
}
