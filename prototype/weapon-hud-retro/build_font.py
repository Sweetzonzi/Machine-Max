font = FontBuilder(800, isTTF=True)
order = ['.notdef'] + [f'u{ord(c):04X}' for c in PATTERNS]
glyphs = {'.notdef': TTGlyphPen(None).glyph()}
for char, pattern in PATTERNS.items():
    pen = TTGlyphPen(None)
    for row, cells in enumerate(pattern.split()):
        for col, cell in enumerate(cells):
            if cell == '1':
                x, y = col * 100, (6 - row) * 100
                pen.moveTo((x, y)); pen.lineTo((x, y + 100))
                pen.lineTo((x + 100, y + 100)); pen.lineTo((x + 100, y))
                pen.closePath()
    glyphs[f'u{ord(char):04X}'] = pen.glyph()
font.setupGlyphOrder(order)
cmap = {ord(c): f'u{ord(c):04X}' for c in PATTERNS}
cmap.update({ord(c.lower()): f'u{ord(c):04X}' for c in PATTERNS if c.isalpha()})
font.setupCharacterMap(cmap)
font.setupGlyf(glyphs)
font.setupHorizontalMetrics({g: (600, 0) for g in order})
font.setupHorizontalHeader(ascent=700, descent=-100)
font.setupNameTable({'familyName': 'MM Field', 'styleName': 'Regular', 'uniqueFontIdentifier': 'MMField5x7-1', 'fullName': 'MM Field 5x7', 'psName': 'MMField5x7'})
font.setupOS2(sTypoAscender=700, sTypoDescender=-100, usWinAscent=700, usWinDescent=100)
font.setupPost()
font.save(Path(__file__).parent / 'assets' / 'mm-field.ttf')
